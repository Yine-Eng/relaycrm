-- RelayCRM schema.
-- Tenant isolation is enforced here in three ways:
--   1. every CRM row carries org_id;
--   2. composite foreign keys make cross-organization references impossible
--      (a record's owner, and an opportunity's contact, must be in the same org);
--   3. row-level security hides every row whose org_id is not the session's
--      app.current_org, which the application sets at the start of each transaction.

CREATE TABLE organizations (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE users (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id       bigint NOT NULL REFERENCES organizations (id),
    email        text   NOT NULL UNIQUE,
    name         text   NOT NULL,
    role         text   NOT NULL CHECK (role IN ('ADMIN', 'MANAGER', 'REP')),
    api_key_hash text   NOT NULL UNIQUE,            -- SHA-256 hex of the API key (stub auth)
    UNIQUE (org_id, id)                             -- target for composite foreign keys
);

CREATE TABLE contacts (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id     bigint NOT NULL REFERENCES organizations (id),
    owner_id   bigint NOT NULL,
    first_name text   NOT NULL,
    last_name  text   NOT NULL,
    email      text,
    phone      text,
    company    text,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    UNIQUE (org_id, id),
    FOREIGN KEY (org_id, owner_id) REFERENCES users (org_id, id)
);

CREATE TABLE leads (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id     bigint NOT NULL REFERENCES organizations (id),
    owner_id   bigint NOT NULL,
    name       text   NOT NULL,
    company    text,
    email      text,
    source     text,
    status     text   NOT NULL CHECK (status IN ('NEW', 'CONTACTED', 'QUALIFIED', 'DISQUALIFIED')),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    FOREIGN KEY (org_id, owner_id) REFERENCES users (org_id, id)
);

CREATE TABLE opportunities (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id     bigint NOT NULL REFERENCES organizations (id),
    owner_id   bigint NOT NULL,
    contact_id bigint,
    name       text   NOT NULL,
    amount     numeric(14, 2),
    stage      text   NOT NULL CHECK (stage IN ('PROSPECTING', 'PROPOSAL', 'NEGOTIATION', 'WON', 'LOST')),
    close_date date,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    FOREIGN KEY (org_id, owner_id)   REFERENCES users (org_id, id),
    FOREIGN KEY (org_id, contact_id) REFERENCES contacts (org_id, id)
);

CREATE INDEX leads_org_idx         ON leads (org_id, id);
CREATE INDEX opportunities_org_idx ON opportunities (org_id, id);

-- Row-level security -------------------------------------------------------
-- If app.current_org is not set the expression is NULL, so no row is visible
-- and no row can be written: the policy fails closed.

ALTER TABLE contacts      ENABLE ROW LEVEL SECURITY;
ALTER TABLE leads         ENABLE ROW LEVEL SECURITY;
ALTER TABLE opportunities ENABLE ROW LEVEL SECURITY;
ALTER TABLE contacts      FORCE ROW LEVEL SECURITY;
ALTER TABLE leads         FORCE ROW LEVEL SECURITY;
ALTER TABLE opportunities FORCE ROW LEVEL SECURITY;

CREATE POLICY tenant_isolation ON contacts
    USING      (org_id = NULLIF(current_setting('app.current_org', true), '')::bigint)
    WITH CHECK (org_id = NULLIF(current_setting('app.current_org', true), '')::bigint);

CREATE POLICY tenant_isolation ON leads
    USING      (org_id = NULLIF(current_setting('app.current_org', true), '')::bigint)
    WITH CHECK (org_id = NULLIF(current_setting('app.current_org', true), '')::bigint);

CREATE POLICY tenant_isolation ON opportunities
    USING      (org_id = NULLIF(current_setting('app.current_org', true), '')::bigint)
    WITH CHECK (org_id = NULLIF(current_setting('app.current_org', true), '')::bigint);

-- Restricted role the application connects as ------------------------------

DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '${appUser}') THEN
        CREATE ROLE ${appUser} LOGIN PASSWORD '${appPassword}' NOSUPERUSER NOBYPASSRLS;
    END IF;
END
$$;

GRANT SELECT ON organizations, users TO ${appUser};
GRANT SELECT, INSERT, UPDATE, DELETE ON contacts, leads, opportunities TO ${appUser};
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO ${appUser};
