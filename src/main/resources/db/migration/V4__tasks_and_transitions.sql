-- Follow-up tasks, created by hand or automatically when a deal or a lead
-- reaches a certain stage.

-- Tasks point at leads and opportunities with composite foreign keys, which
-- need a unique (org_id, id) to point at. contacts already has one. The new
-- constraints come with their own index, so the old plain indexes can go.
ALTER TABLE leads         ADD CONSTRAINT leads_org_id_id_key         UNIQUE (org_id, id);
ALTER TABLE opportunities ADD CONSTRAINT opportunities_org_id_id_key UNIQUE (org_id, id);
DROP INDEX leads_org_idx;
DROP INDEX opportunities_org_idx;

CREATE TABLE tasks (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id         bigint NOT NULL REFERENCES organizations (id),
    owner_id       bigint NOT NULL,
    title          text   NOT NULL,
    due_at         timestamptz NOT NULL,
    status         text   NOT NULL CHECK (status IN ('OPEN', 'DONE', 'CANCELLED')),
    source         text   NOT NULL CHECK (source IN ('AUTO', 'MANUAL')),
    opportunity_id bigint,
    lead_id        bigint,
    -- Set for automatic tasks only, for example 'opportunity:107:proposal-follow-up'.
    dedupe_key     text,
    created_at     timestamptz NOT NULL,
    updated_at     timestamptz NOT NULL,
    version        bigint NOT NULL DEFAULT 0,
    UNIQUE (org_id, id),
    -- A task is about one deal, or one lead, or neither; never both.
    CHECK (num_nonnulls(opportunity_id, lead_id) <= 1),
    CHECK ((source = 'AUTO') = (dedupe_key IS NOT NULL)),
    FOREIGN KEY (org_id, owner_id) REFERENCES users (org_id, id),
    -- When the deal or lead is deleted, the task stays and only its link is
    -- cleared. The column list matters: a plain ON DELETE SET NULL would set
    -- org_id to NULL as well.
    FOREIGN KEY (org_id, opportunity_id) REFERENCES opportunities (org_id, id) ON DELETE SET NULL (opportunity_id),
    FOREIGN KEY (org_id, lead_id)        REFERENCES leads (org_id, id)         ON DELETE SET NULL (lead_id)
);

-- Duplicate prevention, in the database: at most one OPEN task per key in an
-- organization. Finished tasks are not covered, so once a task is DONE or
-- CANCELLED the same key can be used again.
CREATE UNIQUE INDEX tasks_one_open_per_key ON tasks (org_id, dedupe_key) WHERE status = 'OPEN';

-- The task list: one owner's (or everyone's) tasks by status, soonest first.
CREATE INDEX tasks_list_idx ON tasks (org_id, owner_id, status, due_at);

-- "The tasks of this deal / this lead", and the foreign keys' own lookups.
CREATE INDEX tasks_opportunity_idx ON tasks (org_id, opportunity_id) WHERE opportunity_id IS NOT NULL;
CREATE INDEX tasks_lead_idx        ON tasks (org_id, lead_id)        WHERE lead_id IS NOT NULL;

-- Row-level security: the same rule as every other tenant table -------------

ALTER TABLE tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE tasks FORCE ROW LEVEL SECURITY;

CREATE POLICY tenant_isolation ON tasks
    USING      (org_id = NULLIF(current_setting('app.current_org', true), '')::bigint)
    WITH CHECK (org_id = NULLIF(current_setting('app.current_org', true), '')::bigint);

GRANT SELECT, INSERT, UPDATE, DELETE ON tasks TO ${appUser};

-- Tasks are audited like the other records ---------------------------------

ALTER TABLE audit_events DROP CONSTRAINT audit_events_entity_type_check;
ALTER TABLE audit_events ADD CONSTRAINT audit_events_entity_type_check
    CHECK (entity_type IN ('CONTACT', 'LEAD', 'OPPORTUNITY', 'TASK'));
